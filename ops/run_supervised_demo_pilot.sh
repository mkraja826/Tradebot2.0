#!/usr/bin/env bash
# One supervised 20-minute Delta India DEMO execution test.
# NOT a 24/7 service. This script can submit a real TESTNET order.
set -euo pipefail
set +x
umask 077

if [[ "$(id -u)" -eq 0 ]]; then
  echo "Run this as your normal VM SSH user, not root." >&2
  exit 1
fi

PROJECT="$(cd -- "$(dirname -- "$0")/.." && pwd -P)"
KEY_FILE="$HOME/.config/tradebot2/keys.env"
HALT_FILE="$PROJECT/data/trades.jsonl.crypto24x7-halt"
PYTHON="$PROJECT/.venv/bin/python"
BOT="$PROJECT/.venv/bin/tradebot"

if [[ ! -r "$KEY_FILE" || ! -x "$PYTHON" || ! -x "$BOT" ]]; then
  echo "Tradebot project, virtual environment, or private credentials missing." >&2
  exit 1
fi
if [[ -e "$HALT_FILE" ]]; then
  echo "A previous critical crypto24x7 halt exists. Review positions and fills; do NOT delete the halt to bypass review." >&2
  exit 1
fi
if command -v systemctl >/dev/null && systemctl is-active --quiet tradebot2-observe.service; then
  echo "Read-only observer is already running; stop it first: sudo systemctl stop tradebot2-observe" >&2
  exit 1
fi
if ! command -v timeout >/dev/null; then
  echo "GNU timeout is required for a bounded supervised pilot." >&2
  exit 1
fi

cd "$PROJECT"
mkdir -p data
chmod 700 data
# Generated by the one-time sealed transfer; secrets are not printed.
# shellcheck disable=SC1090
source "$KEY_FILE"

echo "Checking that the Delta INDIA DEMO account is flat before the first order..."
"$PYTHON" -m tradebot.pilot_verify ||
  { echo "Stop: account has exposure, open orders or invalid exchange read." >&2; exit 2; }

echo
echo "STARTING ONE SUPERVISED DEMO DECISION WINDOW (up to 20 minutes)."
echo "BTC futures/options only, up to four legs of one contract each."
echo "The AI can choose WAIT. Maximum position hold: five minutes."
echo "Do not close the SSH terminal; an exit is not guaranteed if Delta fails."
echo "Review API permissions, logs, and trades in the demo exchange."
echo

# This explicitly enables only testnet mutations for this child process.
# 1-hour decision cooldown means at most one AI entry attempt in this
# 20-minute test; no automatic chain of trades.
set +e
ENABLE_DEMO_ORDERS=true ALLOW_CRYPTO_24X7_DEMO=true \
  timeout --signal=TERM --kill-after=120s 1200s \
  "$BOT" run --mode demo --schedule crypto-24x7 --demo-execute \
  --max-options 32 --poll-seconds 5 --ai-interval-seconds 3600 \
  --max-hold-minutes 5
status=$?
set -e

echo
echo "Checking all BTC positions and open orders AGAINST Delta testnet..."
if "$PYTHON" -m tradebot.pilot_verify; then
  echo "DEMO ACCOUNT FLAT VERIFIED AFTER PILOT."
else
  echo "CRITICAL: Testnet exposure is not verified flat. Inspect Delta Demo account manually NOW." >&2
  exit 2
fi
if [[ "$status" -eq 0 || "$status" -eq 124 ]]; then
  echo "Pilot ended. No autonomous 24-hour trading service has been enabled."
else
  echo "Pilot process ended abnormally (exit $status); investigate before another order." >&2
  exit "$status"
fi
